const NAME_TO_ISO: Record<string, string> = Object.fromEntries(
  Object.entries(ISO_TO_NAME).map(([iso, name]) => [normalize(name), iso]),
);

function normalize(value: string): string {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toUpperCase()
    .replace(/[^A-Z]/g, '');
}

const BRACKET_PATTERN = /\[([A-Za-z]{2})\]/g;

function fromBracket(value: string): string | null {
  BRACKET_PATTERN.lastIndex = 0;
  let match: RegExpExecArray | null;
  while ((match = BRACKET_PATTERN.exec(value)) !== null) {
    const iso = match[1].toUpperCase();
    if (ISO_TO_NAME[iso]) return ISO_TO_NAME[iso];
  }
  return null;
}

function fromFlag(value: string): string | null {
  for (const flag of Object.keys(FLAG_TO_ISO)) {
    if (value.includes(flag)) return ISO_TO_NAME[FLAG_TO_ISO[flag]];
  }
  return null;
}

function fromName(value: string): string | null {
  const normalized = normalize(value);
  for (const name of Object.keys(NAME_TO_ISO)) {
    if (normalized.includes(name)) return ISO_TO_NAME[NAME_TO_ISO[name]];
  }
  return null;
}

export function detectCountry(title: string, groupTitle?: string): string | null {
  const candidates = [title, groupTitle ?? ''];
  for (const candidate of candidates) {
    const fromB = fromBracket(candidate);
    if (fromB) return fromB;
  }
  for (const candidate of candidates) {
    const fromF = fromFlag(candidate);
    if (fromF) return fromF;
  }
  for (const candidate of candidates) {
    const fromN = fromName(candidate);
    if (fromN) return fromN;
  }
  return null;
}
